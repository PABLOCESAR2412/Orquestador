export function AppNav({
  variant = "sidebar",
  onItemClick,
}: {
  variant?: "sidebar" | "row" | "rail";
  onItemClick?: () => void;
}) {
  if (variant !== "sidebar") {
    return (
      <nav className={`app-nav app-nav-${variant}`} aria-label="Principal">
        {ITEMS.map((item) => (
          <Link
            key={item.to}
            to={item.to}
            className="app-link"
            activeProps={{ className: "app-link active", "aria-current": "page" as const }}
            onClick={onItemClick}
          >
            {item.label}
          </Link>
        ))}
      </nav>
    );
  }

  return (
    <nav className="sidebar-nav" aria-label="Navegación principal">
      {ITEMS.map((item) => (
        <Link
          key={item.to}
          to={item.to}
          className="sidebar-link"
          activeProps={{ className: "sidebar-link active", "aria-current": "page" as const }}
          onClick={onItemClick}
        >
          <span className="sidebar-link-icon">{item.icon}</span>
          <span className="sidebar-link-label">{item.label}</span>
        </Link>
      ))}
    </nav>
  );
}
